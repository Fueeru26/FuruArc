/** Language of the Str instance (used by the companion text classes). */
fun Str.langOf(): Lang = when {
    this === Strings.ID -> Lang.ID
    this === StrCjk.JA -> Lang.JA
    this === StrCjk.ZH -> Lang.ZH
    this === StrCjk.KO -> Lang.KO
    else -> Lang.EN
}
